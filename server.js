// SMART AI SUMMARIZER (Bilingual)
// ============================================================
function summarizeAI(text) {
  let cleanText = (text || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
  let lower = cleanText.toLowerCase();
  
  if (lower.includes('no ai') || lower.includes('walang ai') || lower.includes('did not use ai')) {
    return { 
      en: "❌ No AI was used (Pure Human Work).", 
      fil: "❌ Walang AI na ginamit (Purong Gawa ng Guro)." 
    };
  }

  if (lower.includes('prohibited') || lower.includes('ai-generated lesson plan')) {
    return { 
      en: "🚫 Prohibited: The entire lesson plan was generated by AI.", 
      fil: "🚫 Ipinagbabawal: Ang buong lesson plan ay ginawa ng AI." 
    };
  }

  let aiTool = "AI";
  if (lower.includes('chatgpt')) aiTool = "ChatGPT";
  else if (lower.includes('grammarly')) aiTool = "Grammarly";
  else if (lower.includes('gemini') || lower.includes('bard')) aiTool = "Google Gemini";
  else if (lower.includes('claude')) aiTool = "Claude AI";

  let purposeEn = "as a teaching aid";
  let purposeFil = "bilang pantulong sa pagtuturo";

  if (lower.includes('learning objectives') || lower.includes('develop learning objectives') || lower.includes('layunin')) {
    purposeEn = "to develop Learning Objectives";
    purposeFil = "upang bumuo ng Learning Objectives";
  } else if (lower.includes('grammar') || lower.includes('spelling')) {
    purposeEn = "for grammar and spelling check";
    purposeFil = "para sa grammar at spelling check";
  } else if (lower.includes('formatting') || lower.includes('layout')) {
    purposeEn = "for formatting and layout";
    purposeFil = "para sa formatting at layout";
  } else if (lower.includes('rephrasing') || lower.includes('refining')) {
    purposeEn = "for rephrasing text";
    purposeFil = "para sa pag-rephrase ng text";
  } else if (lower.includes('translation') || lower.includes('translate')) {
    purposeEn = "for translation assistance";
    purposeFil = "para sa pagsasalin (translation)";
  }

  let affirmationsEn = [];
  let affirmationsFil = [];

  if (lower.includes('reviewed') || lower.includes('validated') || lower.includes('edited') || lower.includes('adapted')) {
    affirmationsEn.push("Reviewed and validated by the teacher");
    affirmationsFil.push("Sinuri at ni-validate ng guro");
  }
  if (lower.includes('no confidential') || lower.includes('no sensitive') || lower.includes('walang confidential') || lower.includes('walang sensitive')) {
    affirmationsEn.push("No confidential data was shared");
    affirmationsFil.push("Walang confidential na datos na ibinahagi");
  }

  let summaryEn = `🤖 Used ${aiTool} ${purposeEn}.`;
  if (affirmationsEn.length > 0) {
    summaryEn += ` ✅ ${affirmationsEn.join(" and ")}.`;
  }

  let summaryFil = `🤖 Gumamit ng ${aiTool} ${purposeFil}.`;
  if (affirmationsFil.length > 0) {
    summaryFil += ` ✅ ${affirmationsFil.join(" at ")}.`;
  }

  return { en: summaryEn, fil: summaryFil };
}

